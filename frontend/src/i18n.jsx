// Make every English string in the key-based dictionary available to the
// automatic page translator (covers text rendered without t()).
(() => {
  const { en, mr, hi } = TRANSLATIONS;
  const keys = new Set([...Object.keys(mr), ...Object.keys(hi)]);
  keys.forEach((k) => {
    const english = en[k] !== undefined ? en[k] : (/[A-Za-z]/.test(k) && !/^[a-z0-9_]+$/.test(k) ? k : null);
    if (english) registerPhrase(english, mr[k], hi[k]);
  });
})();

const LanguageContext = createContext({
  language: 'en',
  setLanguage: () => {},
  t: (key, fallback) => fallback || key,
  languages: LANGUAGES
});

export const LanguageProvider = ({ children }) => {
  const [language, setLanguageState] = useState(() => {
    try {
      const saved = localStorage.getItem('arthayog_lang');
      if (saved && TRANSLATIONS[saved]) return saved;
    } catch (e) {}
    return 'en';
  });

  const setLanguage = (lang) => {
    if (TRANSLATIONS[lang]) {
      setLanguageState(lang);
      try {
        localStorage.setItem('arthayog_lang', lang);
      } catch (e) {}
    }
  };

  const t = (key, fallback = '') => {
    if (!key) return fallback || '';
    const currentDict = TRANSLATIONS[language] || TRANSLATIONS.en;
    
    // 1. Direct key match in active language
    if (currentDict && currentDict[key] !== undefined) {
      return currentDict[key];
    }
    
    // 2. English text (dictionary value or supplied fallback)
    const english = (TRANSLATIONS.en && TRANSLATIONS.en[key] !== undefined)
      ? TRANSLATIONS.en[key]
      : (fallback || key);

    // 3. Translate the English text via the phrase dictionary
    if (language !== 'en' && typeof english === 'string') {
      const translated = translatePhrase(english, language);
      if (translated !== null) return translated;
    }

    return english;
  };

  // Translate any remaining hard-coded English text on the page
  useLayoutEffect(() => {
    applyAutoTranslate(language);
  }, [language]);

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, languages: LANGUAGES }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);

